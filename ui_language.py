class UiLanguage:
    """Translate visible strings and update widgets in place."""

    def __init__(self):
        self.settings = QSettings("ArtefactsOrthoMaker", "ArtefactsOrthoMaker")
        self.code = self.settings.value("ui/language", "ja")
        self.bindings = {}

    def text(self, source):
        if self.code != "en" or not source:
            return source
        if source in ENGLISH:
            return ENGLISH[source]
        return _FRAGMENTS.sub(lambda match: ENGLISH[match[0]], source)

    def source(self, widget, setter):
        return self.bindings[(id(widget), setter)][1]

    def bind(self, widget, setter, source, *, translate=True):
        key = (id(widget), setter)
        if key not in self.bindings:
            widget.destroyed.connect(lambda *_: self.bindings.pop(key, None))
        apply = getattr(widget, setter)
        self.bindings[key] = (apply, source, translate)
        apply(self.text(source) if translate else source)

    def register(self, root):
        """Capture the text created by a window's UI builder."""
        self.bind(root, "setWindowTitle", root.windowTitle())
        for cls, getter, setter in (
            (QtWidgets.QLabel, "text", "setText"),
            (QtWidgets.QAbstractButton, "text", "setText"),
            (QtWidgets.QGroupBox, "title", "setTitle"),
            (QtWidgets.QMenu, "title", "setTitle"),
            (QAction, "text", "setText"),
        ):
            for widget in root.findChildren(cls):
                key = (id(widget), setter)
                if key not in self.bindings:
                    self.bind(widget, setter, getattr(widget, getter)())
        self._refresh_options(root)

    def _refresh_options(self, root):
        for combo in root.findChildren(QtWidgets.QComboBox):
            if combo.property("translatedOptions"):
                self._translate_combo(combo)
        for table in root.findChildren(QtWidgets.QTableWidget):
            sources = table.property("headerSources")
            if sources:
                table.setHorizontalHeaderLabels([self.text(source) for source in sources])

    def _translate_combo(self, combo):
        with QSignalBlocker(combo):
            for index in range(combo.count()):
                combo.setItemText(index, self.text(combo.itemData(index)))

    def set_language(self, code, root):
        self.code = code
        self.settings.setValue("ui/language", code)
        for setter, source, translate in list(self.bindings.values()):
            setter(self.text(source) if translate else source)
        self._refresh_options(root)
